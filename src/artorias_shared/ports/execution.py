"""Execution boundaries; remote implementations must preserve these contracts."""
from typing import Protocol, Callable, Any, AsyncContextManager

class WorkspacePort(Protocol):
    def describe(self) -> dict: ...
    def files(self) -> list[str]: ...
    def path(self, path: str) -> str: ...
    def read_version(self, path: str) -> tuple[str, str]: ...
    def read_bytes(self, path: str) -> bytes: ...
    def head(self, path: str) -> str | None: ...
    def write(self, path: str, content: str, *, expected: str | None) -> dict: ...
    def delete(self, path: str) -> str: ...

class SandboxExecutor(Protocol):
    async def run_python(self, workspace: WorkspacePort, path: str) -> dict: ...

class CheckpointProvider(Protocol):
    def open(self) -> AsyncContextManager[Any]: ...

WorkspaceFactory = Callable[[dict], WorkspacePort]


class PythonWorkspacePort(WorkspacePort, Protocol):
    session: str
    run: str | None
    task: str | None
    def check_access(self, path: str, action: str = 'read') -> None: ...
    def files_under(self, directory: str) -> list[str]: ...
    def read_binary_version(self, path: str) -> tuple[bytes, str]: ...
    def write_bytes(self, path: str, content: bytes, *, expected: str | None, operation_id: str | None = None) -> dict: ...
    def delete_version(self, path: str, *, expected: str, operation_id: str | None = None) -> dict: ...
