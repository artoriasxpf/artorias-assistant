"""Resource contracts. No filesystem, database or agent-framework dependencies."""
from collections.abc import Iterator
from dataclasses import dataclass
from typing import Literal, NotRequired, Protocol, TypedDict

UNSET_VERSION = object()


@dataclass(frozen=True)
class WorkspaceContext:
    session_id: str
    run_id: str | None = None
    task_id: str | None = None


@dataclass(frozen=True)
class ResourceRef:
    backend: str
    location_id: str
    path: str
    workspace_id: str | None = None


@dataclass(frozen=True)
class BlobRef:
    store_id: str
    sha256: str


class BlobStore(Protocol):
    def put(self, data: bytes) -> BlobRef: ...
    def get(self, ref: BlobRef) -> bytes: ...


class DirectoryEntry(TypedDict):
    path: str
    type: Literal['file', 'directory']


class DirectoryTree(TypedDict):
    entries: list[DirectoryEntry]
    truncated: bool
    filters: NotRequired[dict]
    coverage: NotRequired[dict]
    stop_reason: NotRequired[str]


class FileOperations(Protocol):
    def path(self, path: str) -> str: ...
    def files(self) -> list[str]: ...
    def list_directory(self, directory: str) -> list[DirectoryEntry]: ...
    def tree(self, directory: str, *, max_depth: int, max_entries: int, include_hidden: bool) -> DirectoryTree: ...
    def read_bytes(self, path: str) -> bytes: ...
    def read_version(self, path: str) -> tuple[str, str]: ...
    def head(self, path: str) -> str | None: ...
    def write(self, path: str, content: str, expected, reverts=None) -> dict: ...
    def delete(self, path: str) -> str: ...
    def revert(self, change_id: str) -> str: ...
    def read_binary_version(self, path: str) -> tuple[bytes, str]: ...
    def write_bytes(self, path: str, content: bytes, *, expected: str | None, operation_id: str | None = None) -> dict: ...
    def delete_version(self, path: str, *, expected: str, operation_id: str | None = None) -> dict: ...


class AnalysisOperations(Protocol):
    """Optional bounded analysis capabilities of a workspace endpoint."""

    def analysis_entries(self, directory: str, *, max_depth: int,
                         include_hidden: bool) -> Iterator[dict]: ...
    def analysis_range(self, path: str, **options) -> dict: ...
    def analysis_inventory_page(self, path: str, **options) -> dict: ...
    def analysis_search_page(self, path: str, **options) -> dict: ...
    def analysis_search(self, path: str, **options) -> dict: ...
    def analysis_text(self, path: str, *, max_bytes: int, versioned: bool) -> dict: ...


class Connector(Protocol):
    def open(self, workspace: dict, context: WorkspaceContext) -> FileOperations: ...


class ConnectorUnavailable(RuntimeError):
    pass


class ChangeLookup(Protocol):
    def find_change(self, change_id: str, session_id: str) -> dict | None: ...
    def list_changes(self, session_id: str) -> list[dict]: ...


class WorkspaceJournal(Protocol):
    @property
    def data_root(self) -> str: ...
    def binding(self, session: str) -> str | None: ...
    def bind(self, session: str, root: str) -> str: ...
    def pending(self, root: str | None = None) -> list[dict]: ...
    def prepare(self, operation: dict, resource: dict | None) -> None: ...
    def finish(self, operation: dict) -> None: ...
    def abort(self, operation_id: str) -> None: ...
    def committed(self, change_id: str, session: str, root: str) -> dict | None: ...
